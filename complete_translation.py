def process_po_file():
    """Process the PO file and translate empty msgstr entries."""
    input_file = '/Users/jeremy/GitHub/crm/crm/locale/fr.po'

    print(f"Processing {input_file}...")

    with open(input_file, 'r', encoding='utf-8') as f:
        content = f.read()

    # Split into lines for processing
    lines = content.split('\n')

    translated_count = 0
    i = 0

    while i < len(lines):
        line = lines[i]

        # Look for msgid lines
        if line.startswith('msgid '):
            # Extract msgid value
            msgid_match = re.match(r'msgid "(.*)"$', line)
            if msgid_match:
                msgid_value = msgid_match.group(1)

                # Check if next line is empty msgstr
                if i + 1 < len(lines) and lines[i + 1] == 'msgstr ""':
                    # Try to translate
                    translation = translate_text(msgid_value)
                    if translation:
                        # Replace empty msgstr with translation
                        lines[i + 1] = f'msgstr "{translation}"'
                        translated_count += 1
                        if translated_count % 100 == 0:
                            print(f"Translated {translated_count} strings...")

        i += 1

    # Write back to file
    with open(input_file, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))

    print(f"\nTranslation complete!")
    print(f"Total strings translated: {translated_count}")

    return translated_count

